  const SPRACHEN = ["de", "en"];
  const SCHLUESSEL = "brain-sprache";

  function lies(k) { try { return root.localStorage ? root.localStorage.getItem(k) : null; } catch (e) { return null; } }
  function schreib(k, v) { try { if (root.localStorage) root.localStorage.setItem(k, v); } catch (e) { /* gesperrt */ } }

  function ermittle() {
    const gemerkt = lies(SCHLUESSEL);
    if (SPRACHEN.indexOf(gemerkt) >= 0) return gemerkt;
    const nav = root.navigator && typeof root.navigator.language === "string" ? root.navigator.language.slice(0, 2).toLowerCase() : "";
    return SPRACHEN.indexOf(nav) >= 0 ? nav : "de";
  }

  let sprache = ermittle();

  function t(schluessel, werte) {
    const tab = TEXTE[sprache] || TEXTE.de;
    let s = Object.prototype.hasOwnProperty.call(tab, schluessel) ? tab[schluessel]
      : Object.prototype.hasOwnProperty.call(TEXTE.de, schluessel) ? TEXTE.de[schluessel] : String(schluessel);
    if (werte) s = s.replace(/\{(\w+)\}/g, (m, k) => (Object.prototype.hasOwnProperty.call(werte, k) ? String(werte[k]) : m));
    return s;
  }

  function setzeSprache(s) {
    if (SPRACHEN.indexOf(s) < 0) return false;
    sprache = s;
    schreib(SCHLUESSEL, s);
    const doc = root.document;
    if (doc) {
      if (doc.documentElement) doc.documentElement.lang = s;
      if (typeof doc.dispatchEvent === "function" && typeof root.CustomEvent === "function") {
        doc.dispatchEvent(new root.CustomEvent("brain:sprache", { detail: { sprache: s } }));
      }
    }
    return true;
  }

  // Sprache aus den Ansichtsdaten (D.sprache, aus cfg.ansicht.sprache) — nur solange der Nutzer nicht selbst
  // über setzeSprache() gewählt hat (sonst stünde schon ein Wert im localStorage). Schreibt NICHT ins
  // localStorage, damit eine spätere echte Nutzerwahl weiterhin Vorrang hat und eine geänderte Config beim
  // nächsten Laden wieder greift. Löst — anders als setzeSprache() — KEIN „brain:sprache“-Ereignis aus: der
  // Aufrufer kennt den richtigen Zeitpunkt zum Neuzeichnen (z. B. vor dem Aufbau der Daten, wenn die Anzeige
  // ohnehin noch nicht steht) und vermeidet so einen Neuaufbau mit noch nicht gesetztem Zustand.
  function ausConfig(s) {
    if (SPRACHEN.indexOf(s) < 0) return false;
    if (lies(SCHLUESSEL) !== null) return false; // Nutzer hat schon selbst gewählt
    if (s === sprache) return false;
    sprache = s;
    if (root.document && root.document.documentElement) root.document.documentElement.lang = s;
    return true;
  }

  function ergaenze(paket) {
    if (!paket || typeof paket !== "object") return;
    for (const s of SPRACHEN) {
      const neu = paket[s];
      if (!neu || typeof neu !== "object") continue;
      for (const k of Object.keys(neu)) if (typeof neu[k] === "string") TEXTE[s][k] = neu[k];
    }
  }

  if (root.document && root.document.documentElement) root.document.documentElement.lang = sprache;

  root.BrainTexte = {
    t: t,
    get sprache() { return sprache; },
    setzeSprache: setzeSprache,
    ausConfig: ausConfig,
    ergaenze: ergaenze,
    sprachen: SPRACHEN.slice(),
    tabelle: TEXTE,
  };
